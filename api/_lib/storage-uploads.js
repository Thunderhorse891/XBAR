import { requireWorkspaceAccess } from './supabase-admin.js';
import { applyCors } from './cors.js';
import { sendJson } from './http.js';
import { enforceRateLimit } from './rate-limit.js';
import { isWorkspaceId } from './document-storage.js';
import {
  createUploadService,
  publicUpload,
  uploadErrorResult,
  StorageUploadError,
  MAX_UPLOAD_PART_BATCH,
  UPLOAD_URL_TTL_SECONDS,
} from './storage-upload.js';

const MAX_JSON_BYTES = 16 * 1024;
async function readSmallJson(req) {
  const length = req.headers?.['content-length'];
  if (length && (!/^\d+$/.test(length) || Number(length) > MAX_JSON_BYTES))
    throw new StorageUploadError(413, 'request_too_large', 'Upload control requests must be small JSON messages.');
  if (!/^application\/json(?:\s*;|$)/i.test(req.headers?.['content-type'] || ''))
    throw new StorageUploadError(415, 'invalid_content_type', 'Use application/json for upload control requests.');
  let size = 0;
  const chunks = [];
  for await (const chunk of req) {
    const bytes = Buffer.from(chunk);
    size += bytes.length;
    if (size > MAX_JSON_BYTES)
      throw new StorageUploadError(413, 'request_too_large', 'Upload control requests must be small JSON messages.');
    chunks.push(bytes);
  }
  try {
    const body = JSON.parse(Buffer.concat(chunks).toString('utf8'));
    if (!body || Array.isArray(body) || typeof body !== 'object') throw new Error();
    return body;
  } catch {
    throw new StorageUploadError(400, 'invalid_json', 'Request body must be valid JSON.');
  }
}

export function createUploadHandler({
  authorize = requireWorkspaceAccess,
  makeService = createUploadService,
  rateLimit = enforceRateLimit,
} = {}) {
  return async function handler(req, res) {
    res.setHeader('Cache-Control', 'no-store');
    if (!applyCors(req, res)) return;
    if (req.method !== 'POST') return sendJson(res, 405, { ok: false, message: 'Method not allowed.' });
    if (!(await rateLimit(req, res, { bucket: 'storage-uploads', limit: 120, windowSeconds: 60 }))) return;
    let body;
    try {
      body = await readSmallJson(req);
      if (
        !isWorkspaceId(body.workspaceId) ||
        !['create', 'parts', 'complete', 'abort', 'status', 'list'].includes(body.action) ||
        (body.action !== 'list' && !isWorkspaceId(body.requestId))
      )
        throw new StorageUploadError(400, 'invalid_upload', 'A valid workspace, request ID and action are required.');
      // The API never accepts caller-selected keys, provider IDs, completion manifests or upsert.
      if (
        ['storagePath', 'objectPath', 'providerUploadId', 'uploadId', 'parts', 'upsert'].some((key) =>
          Object.hasOwn(body, key),
        )
      )
        throw new StorageUploadError(
          400,
          'invalid_upload',
          'Upload destinations and completion are controlled by the server.',
        );
      const token =
        typeof req.headers?.authorization === 'string'
          ? req.headers.authorization.replace(/^Bearer\s+/i, '').trim()
          : '';
      const access = await authorize(token, body.workspaceId);
      if (!access.ok) return sendJson(res, access.status, { ok: false, message: access.message });
      const service = makeService(access);
      if (body.action === 'list') return sendJson(res, 200, { ok: true, uploads: await service.list() });
      if (body.action === 'create' && body.kind === 'packet')
        throw new StorageUploadError(400, 'invalid_upload', 'Sale packets must be generated by the packet workflow.');
      let row = body.action === 'create' ? await service.create(body) : await service.read(body.requestId);
      if (!row)
        throw new StorageUploadError(404, 'upload_not_found', 'This upload request was not found in this workspace.');
      if (body.action === 'status') row = await service.status(row);
      if (body.action === 'complete') row = await service.complete(row);
      if (body.action === 'abort') row = await service.abort(row);
      const result = { ok: true, upload: publicUpload(row) };
      if (
        body.action === 'parts' ||
        (body.action === 'create' && row.state === 'uploading' && row.provider_upload_id)
      ) {
        const numbers =
          body.action === 'parts'
            ? body.partNumbers
            : Array.from({ length: Math.min(result.upload.partCount, MAX_UPLOAD_PART_BATCH) }, (_, i) => i + 1);
        result.parts = await service.parts(row, numbers);
        result.expiresIn = UPLOAD_URL_TTL_SECONDS;
      }
      return sendJson(res, 200, result);
    } catch (error) {
      return sendJson(
        res,
        error instanceof StorageUploadError ? error.status : 503,
        uploadErrorResult(error, body?.requestId),
      );
    }
  };
}
export default createUploadHandler();
