import { expect, test } from '@playwright/test';

test('a link generated by the running web app reaches the public buyer route in a fresh tab', async ({ page }) => {
  await page.goto('/app/login');
  const token = 'synthetic routing token / + # &';
  const shareUrl = await page.evaluate(async (value) => {
    const modulePath = '/src/lib/facebookSharing.ts';
    const { buildPublicShareUrl } = await import(/* @vite-ignore */ modulePath);
    return buildPublicShareUrl('/profiles/00000000-0000-0000-0000-000000000000', value);
  }, token);

  const buyer = await page.context().newPage();
  try {
    await buyer.goto(shareUrl);
    await expect(buyer.getByRole('heading', { name: 'Sale profile unavailable', exact: true })).toBeVisible();
    // A deliberately nonexistent profile proves route arrival without exposing
    // a real horse/token or bypassing the public-profile authorization boundary.
    expect(new URL(buyer.url()).pathname).toBe('/app/profiles/00000000-0000-0000-0000-000000000000');
    expect(new URL(buyer.url()).searchParams.get('t')).toBe(token);
    expect(new URL(buyer.url()).hash).toBe('');
    await buyer.reload();
    await expect(buyer.getByRole('heading', { name: 'Sale profile unavailable', exact: true })).toBeVisible();
  } finally {
    await buyer.close();
  }
});
